CREATE TABLE user_profile_fields (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (user_id),
    field VARCHAR(40) NOT NULL,
    field_etc VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_profile_fields_user_code UNIQUE (user_id, field),
    CONSTRAINT ck_user_profile_field_etc CHECK (
        CASE WHEN field = 'OTHER'
            THEN field_etc IS NOT NULL AND field_etc ~ '[^[:space:]]'
            ELSE field_etc IS NULL
        END
    )
);
