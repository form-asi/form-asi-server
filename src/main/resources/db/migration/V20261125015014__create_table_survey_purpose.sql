CREATE TABLE IF NOT EXISTS survey_purpose (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id BIGINT NOT NULL REFERENCES survey (id),
    purpose VARCHAR(40) NOT NULL,
    purpose_other VARCHAR(100),
    method VARCHAR(40) NOT NULL,
    method_other VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_survey_purpose_survey_id UNIQUE (survey_id),
    CONSTRAINT ck_survey_purpose_other CHECK (
        CASE WHEN purpose = 'OTHER'
            THEN purpose_other IS NOT NULL AND purpose_other ~ '[^[:space:]]'
            ELSE purpose_other IS NULL
        END
    ),
    CONSTRAINT ck_survey_method_other CHECK (
        CASE WHEN method = 'OTHER'
            THEN method_other IS NOT NULL AND method_other ~ '[^[:space:]]'
            ELSE method_other IS NULL
        END
    )
);
