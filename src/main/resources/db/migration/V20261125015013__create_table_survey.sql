CREATE TABLE IF NOT EXISTS survey (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (user_id),
    title VARCHAR(100) NOT NULL,
    external_url TEXT NOT NULL,
    target_count INTEGER NOT NULL,
    duration_minutes INTEGER NOT NULL,
    pay_minutes INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    target_description VARCHAR(200),
    reward_description VARCHAR(100),
    introduction VARCHAR(700),
    min_age INTEGER,
    max_age INTEGER,
    closed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_survey_target_count CHECK (target_count > 0),
    CONSTRAINT ck_survey_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_survey_pay_minutes CHECK (pay_minutes > 0),
    CONSTRAINT ck_survey_age_range CHECK (
        (min_age IS NULL OR min_age BETWEEN 14 AND 100)
        AND (max_age IS NULL OR max_age BETWEEN 14 AND 100)
        AND (min_age IS NULL OR max_age IS NULL OR min_age <= max_age)
    ),
    CONSTRAINT ck_survey_registration_cost CHECK (target_count::BIGINT * duration_minutes <= 2147483647)
);
