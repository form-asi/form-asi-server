CREATE TABLE signup_bonus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (user_id),
    granted_minutes BIGINT NOT NULL,
    granted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reclaimed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_signup_bonus_user_id UNIQUE (user_id),
    CONSTRAINT ck_signup_bonus_granted_minutes CHECK (granted_minutes > 0),
    CONSTRAINT ck_signup_bonus_expires_at CHECK (expires_at > granted_at)
);
